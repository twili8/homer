#!/usr/bin/env python3
"""Turn a binary into a C array header.

Usage:
    python3 tools/bin2h.py INPUT --out build/instance.h [--instance]

--instance unwraps donut's binary output carrier first: `E8 <len32> <instance>
59 ...`. The build needs only the DONUT_INSTANCE bytes; the call/pop bytes and
the loader body that follow are the shellcode path, not part of the instance.
"""

import argparse
from pathlib import Path


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("input", type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--instance", action="store_true")
    args = ap.parse_args()

    data = args.input.read_bytes()
    if args.instance:
        if len(data) < 5 or data[0] != 0xE8:
            raise SystemExit(f"{args.input}: not an unpacked instance carrier")
        size = int.from_bytes(data[1:5], "little")
        if size == 0 or 5 + size > len(data):
            raise SystemExit(f"{args.input}: declared instance size {size} is out of range")
        data = data[5:5 + size]

    name = "homer_instance"
    guard = "HOMER_INSTANCE_H"
    body = ",".join(str(b) for b in data)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(
        f"/* Generated by tools/bin2h.py from {args.input}. Do not edit. */\n"
        f"#ifndef {guard}\n"
        f"#define {guard}\n\n"
        f"static const unsigned char {name}[] = {{{body}}};\n\n"
        f"#endif\n"
    )
    print(f"wrote {args.out} ({len(data)} bytes)")


if __name__ == "__main__":
    main()
