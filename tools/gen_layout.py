#!/usr/bin/env python3
"""Generate Homer's randomized DONUT_INSTANCE layout.

Usage:
    python3 tools/gen_layout.py --seed N --out include/homer_layout.h

The generated header replaces the in-tree instance struct. Field *names* are
preserved (so donut.c / loader.c keep compiling via offsetof), but field order
within the bootstrap and secret groups is shuffled and random padding arrays
are inserted, so the byte offsets that every upstream parser hard-codes are
wrong for any given Homer build.
"""

import argparse
import random
import re
from pathlib import Path

DONUT_H = Path(__file__).resolve().parent.parent / "include" / "donut_instance_template.h"

HEADER = """#ifndef HOMER_LAYOUT_H
#define HOMER_LAYOUT_H

#include <stdint.h>

/* Generated by tools/gen_layout.py -- seed {seed}. Do not edit by hand. */

typedef struct _DONUT_INSTANCE {{
"""

FOOTER = """} DONUT_INSTANCE, *PDONUT_INSTANCE;

#endif
"""


def split_struct(text: str) -> list[list[str]]:
    """Split the body of DONUT_INSTANCE into top-level field chunks."""
    lines = text.splitlines()
    chunks: list[list[str]] = []
    current: list[str] = []
    depth = 0
    for line in lines:
        stripped = line.strip()
        # track brace depth (preprocessor lines do not change it)
        if not stripped.startswith("#"):
            for ch in line:
                if ch == "{":
                    depth += 1
                elif ch == "}":
                    depth -= 1
        current.append(line)
        if depth == 0 and ";" in stripped and current:
            if any(l.strip() and not l.strip().startswith("//") and not l.strip().startswith("#") for l in current):
                chunks.append(current)
            current = []
    if current and any(l.strip() and not l.strip().startswith("//") for l in current):
        chunks.append(current)
    return chunks


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--out", default="include/homer_layout.h")
    args = ap.parse_args()

    rng = random.Random(args.seed)

    src = DONUT_H.read_text()
    m = re.search(r"typedef struct _DONUT_INSTANCE \{\n(.*?)\n\} DONUT_INSTANCE", src, re.S)
    if not m:
        # template file is just the struct
        body = src[src.index("{")+1:src.rindex("}")]
    else:
        body = m.group(1)
    chunks = split_struct(body)
    if len(chunks) < 6:
        raise SystemExit(f"parsed only {len(chunks)} fields; expected more")

    # bootstrap group: first 3 chunks (len, key, iv) -- shuffled
    boot = chunks[:3]
    rng.shuffle(boot)
    # secret group: api_cnt must stay first (encryption boundary),
    # module must stay last (EMBED memcpy writes from module.x to end of
    # instance), middle fields are shuffled.
    secret = chunks[3:]
    api_cnt_chunk = secret[0]
    # find module chunk (last field that is the module union)
    module_chunk = None
    module_idx = None
    for i in range(len(secret) - 1, 0, -1):
        if "module" in "".join(secret[i]):
            module_chunk = secret.pop(i)
            break
    middle = secret[1:]  # everything between api_cnt and module
    rng.shuffle(middle)
    if module_chunk is not None:
        secret = [api_cnt_chunk] + middle + [module_chunk]
    else:
        secret = [api_cnt_chunk] + middle

    out_lines: list[str] = [HEADER.format(seed=args.seed)]
    pad_idx = 0

    def emit_field(chunk: list[str]) -> None:
        nonlocal pad_idx
        for line in chunk:
            out_lines.append(line)
        # random padding after every field (1..8 bytes)
        k = rng.randint(1, 8)
        out_lines.append(f"    uint8_t homer_pad_{pad_idx}[{k}];")
        pad_idx += 1

    for chunk in boot:
        emit_field(chunk)
    for chunk in secret:
        emit_field(chunk)

    out_lines.append(FOOTER)
    Path(args.out).write_text("\n".join(out_lines) + "\n")
    print(f"wrote {args.out} (seed={args.seed}, {len(chunks)} fields)")


if __name__ == "__main__":
    main()
