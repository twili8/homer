#!/usr/bin/env python3
"""Wire operator passes into Homer's loader.

Usage:
    python3 tools/gen_passes.py --out build/c/passes_gen.c passes/*.c passes/*.cpp
    make -f Makefile.homer dll DLL_PASSES="passes/foo.c" INSTANCE=build/instance.bin
        # DLL table generated from DLL_PASSES only (default: empty)
    python3 tools/gen_passes.py --check-imports build/loader.exe homer_loader.dll

Each file under passes/ that wants to run contains a marker:

    HOMER_REGISTER(name, HOMER_PRE_MAP)   # or HOMER_PRE_JUMP

and defines, in the same file:

    int homer_pass__name(PDONUT_INSTANCE inst, PDONUT_MODULE mod,
                         PVOID base, PIMAGE_NT_HEADERS nt);

(C++ files must wrap the definition in extern "C".) The generated file holds
the whole dispatcher sorted by (stage, name); there is no runtime registry and no
pass limit.

Passes resolve everything through the PEB (inst->api,
xGetProcAddressByHash). Two gates enforce that:

  source gate   banned tokens below fail the build with file:line.
  import gate   --check-imports fails any artifact with an import table;
                the release loader and DLL must import nothing.

Exit codes: 0 ok, 2 on any error.
"""

import argparse
import re
import sys
from pathlib import Path

STAGES = ("HOMER_PRE_MAP", "HOMER_PRE_JUMP")

REGISTER_RE = re.compile(
    r"HOMER_REGISTER\s*\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*,"
    r"\s*(HOMER_PRE_MAP|HOMER_PRE_JUMP)\s*\)"
)

# Direct Win32 calls would add an import to the release artifact. Passes must
# go through inst->api or xGetProcAddressByHash instead.
BANNED_CALLS = (
    "LoadLibraryA", "LoadLibraryW", "GetProcAddress",
    "GetModuleHandleA", "GetModuleHandleW",
    "VirtualAlloc", "VirtualAllocEx", "VirtualProtect", "VirtualProtectEx",
    "CreateThread", "CreateRemoteThread", "WinExec", "ShellExecuteA",
    "ShellExecuteW",
)
BANNED_RE = re.compile(r"\b(" + "|".join(BANNED_CALLS) + r")\s*\(")


def die(msg: str):
    print(f"gen_passes: {msg}", file=sys.stderr)
    sys.exit(2)


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    out = []
    for line in text.splitlines():
        out.append(line.split("//", 1)[0])
    return "\n".join(out)


def scan(path: Path) -> list[tuple[str, str]]:
    try:
        text = path.read_text()
    except OSError as exc:
        die(f"{path}: cannot read ({exc})")
    stripped = strip_comments(text)
    found = REGISTER_RE.findall(stripped)
    if not found:
        return []
    if "__declspec(dllimport)" in stripped:
        die(f"{path}: __declspec(dllimport) is forbidden in passes")
    if re.search(r"#pragma\s+comment", stripped):
        die(f"{path}: #pragma comment(lib) is forbidden in passes")
    m = BANNED_RE.search(stripped)
    if m:
        die(f"{path}: direct Win32 call {m.group(1)}() is forbidden; "
            "resolve through the PEB (inst->api, xGetProcAddressByHash)")
    if path.suffix == ".cpp" and 'extern "C"' not in text:
        die(f"{path}: C++ passes must wrap homer_pass__* in extern \"C\"")
    for name, stage in found:
        if not re.search(r"homer_pass__" + re.escape(name) + r"\s*\(", stripped):
            die(f"{path}: HOMER_REGISTER({name}, ...) without a "
                f"homer_pass__{name} definition in the same file")
    return found


GEN_HEADER = """/* Generated by tools/gen_passes.py. Do not edit. */
#include "pass.h"
"""


def generate(files: list[Path]) -> str:
    entries: list[tuple[str, str]] = []
    seen: dict[str, str] = {}
    for path in files:
        for name, stage in scan(path):
            if name in seen:
                die(f"duplicate pass {name} ({path}, first in {seen[name]})")
            seen[name] = str(path)
            entries.append((stage, name))
    # No pointer table: the release loader runs as unrelocated PIC shellcode,
    # so absolute addresses in .rdata would be garbage. Direct calls are
    # RIP-relative and safe, so the generator emits the dispatcher itself.
    # No runtime registry, no pass limit.
    entries.sort(key=lambda e: (STAGES.index(e[0]), e[1]))
    lines = [GEN_HEADER]
    for stage, name in entries:
        lines.append(
            f"extern int homer_pass__{name}(PDONUT_INSTANCE inst, "
            f"PDONUT_MODULE mod, PVOID base, PIMAGE_NT_HEADERS nt);"
        )
    lines.append("int homer_run_passes(homer_stage_t stage, PDONUT_INSTANCE inst,")
    lines.append("                     PDONUT_MODULE mod, PVOID base, PIMAGE_NT_HEADERS nt) {")
    for stage in STAGES:
        names = [n for s, n in entries if s == stage]
        lines.append(f"    if (stage == {stage}) {{")
        for name in names:
            lines.append(f"        /* pass {name} */")
            lines.append(
                f"        if (homer_pass__{name}(inst, mod, base, nt) != 0) return -1;")
        lines.append("    }")
    lines.append("    (void)stage; (void)inst; (void)mod; (void)base; (void)nt;")
    lines.append("    return 0;")
    lines.append("}")
    return "\n".join(lines) + "\n"


def check_imports(paths: list[Path]) -> int:
    try:
        import pefile
    except ImportError:
        die("pefile is required for --check-imports")
    rc = 0
    for path in paths:
        try:
            pe = pefile.PE(str(path), fast_load=True)
            pe.parse_data_directories(
                directories=[pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_IMPORT"]]
            )
            dlls = [e.dll.decode(errors="replace")
                    for e in getattr(pe, "DIRECTORY_ENTRY_IMPORT", [])]
        except Exception as exc:
            print(f"gen_passes: {path}: cannot verify imports ({exc})",
                  file=sys.stderr)
            rc = 2
            continue
        finally:
            try:
                pe.close()
            except Exception:
                pass
        if dlls:
            print(f"gen_passes: {path}: forbidden imports: "
                  + ", ".join(dlls), file=sys.stderr)
            rc = 2
        else:
            print(f"gen_passes: {path}: no imports")
    return rc


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=None)
    ap.add_argument("--check-imports", nargs="*", default=None,
                    metavar="PE",
                    help="fail if any listed PE has an import table")
    ap.add_argument("files", nargs="*")
    args = ap.parse_args()

    if args.check_imports is not None:
        if not args.check_imports:
            die("--check-imports needs at least one PE")
        sys.exit(check_imports([Path(p) for p in args.check_imports]))

    if args.out is None:
        die("--out is required (or use --check-imports)")
    text = generate([Path(p) for p in args.files])
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(f"gen_passes: wrote {out} "
          f"({text.count('homer_pass__') // 2} passes)")


if __name__ == "__main__":
    main()
